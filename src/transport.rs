use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

pub type Source = Box<dyn Read + Send>;
pub type LidiSender = lidi_send::Sender<Source>;

fn endpoint_label(index: u16) -> String {
    format!("unix:dyode-endpoint-{index}")
}

/// The lidi endpoint that carries the input box's status: the one after
/// the last module, so both boxes agree on it from the same config.yaml.
pub fn status_endpoint(cfg: &Config) -> u16 {
    cfg.modules.len() as u16
}

/// Identifies status messages in their envelopes, as a module tag does.
pub fn status_tag() -> [u8; 8] {
    use sha2::{Digest, Sha256};
    let d = Sha256::digest(b"dyode-module-v1\0status\0dyode-status");
    let mut t = [0u8; 8];
    t.copy_from_slice(&d[..8]);
    t
}

/// The lidi TOML for this config (the same text on both boxes).
///
/// It is what DYODE feeds to lidi's own configuration parser, and what
/// `dyode lidi-config` prints, so the transport can be inspected -- or a
/// standalone lidi-send/lidi-receive pair run with identical parameters.
pub fn lidi_toml(cfg: &Config) -> String {
    let l: &LidiConfig = &cfg.lidi;
    let ports: Vec<String> = l.ports.iter().map(u16::to_string).collect();
    let endpoints: Vec<String> = cfg
        .modules
        .iter()
        .map(|m| m.index)
        .chain(std::iter::once(status_endpoint(cfg)))
        .map(|i| format!("\"{}\"", endpoint_label(i)))
        .collect();
    let send_bind = l
        .send_bind
        .map_or_else(|| format!("{}:0", cfg.network.in_ip), |a| a.to_string());
    let mut t = String::new();
    t.push_str("# Generated by DYODE from config.yaml.  Common parameters must be\n");
    t.push_str("# identical on both sides.\n");
    t.push_str(&format!("mtu = {}\n", l.mtu));
    t.push_str(&format!("ports = [{}]\n", ports.join(", ")));
    t.push_str(&format!("block = {}\n", l.block));
    t.push_str(&format!("repair = {}\n", l.repair));
    t.push_str(&format!("max_clients = {}\n", cfg.max_clients()));
    t.push_str(&format!("heartbeat = {}\n\n", l.heartbeat));
    t.push_str("[send]\n");
    t.push_str(&format!("to = \"{}\"\n", cfg.network.out_ip));
    t.push_str(&format!("to_bind = \"{send_bind}\"\n"));
    if let Some(m) = l.mode {
        t.push_str(&format!("mode = \"{}\"\n", m.as_str()));
    }
    if let Some(p) = l.prometheus_in {
        t.push_str(&format!("prometheus_listen = \"{p}\"\n"));
    }
    t.push_str(&format!("from = [{}]\n\n", endpoints.join(", ")));
    t.push_str("[receive]\n");
    t.push_str(&format!("from = \"{}\"\n", cfg.network.out_ip));
    if let Some(m) = l.mode {
        t.push_str(&format!("mode = \"{}\"\n", m.as_str()));
    }
    t.push_str(&format!("reset_timeout = {}\n", l.reset_timeout));
    if let Some(a) = l.abort_timeout {
        t.push_str(&format!("abort_timeout = {a}\n"));
    }
    t.push_str(&format!("client_queue_size = {}\n", l.client_queue_size));
    if let Some(p) = l.prometheus_out {
        t.push_str(&format!("prometheus_listen = \"{p}\"\n"));
    }
    t.push_str(&format!("to = [{}]\n", endpoints.join(", ")));
    t
}

/// The air parameters, as `dyode lidi-config` prints them for an air
/// configuration.
pub fn air_summary(cfg: &Config) -> String {
    let a = &cfg.air;
    let mut t = String::new();
    t.push_str("# transport: air -- lidi is not used.  Generated by DYODE from config.yaml.\n");
    t.push_str("# symbol and chunk must be identical on both boxes; the rest is one side's.\n");
    t.push_str(&format!("symbol = {}\nchunk = {}\n", a.symbol, a.chunk));
    t.push_str(&format!(
        "packet = {}   # bytes per datagram: symbol + {} of header and tag\n",
        usize::from(a.symbol) + crate::config::AirConfig::OVERHEAD,
        crate::config::AirConfig::OVERHEAD
    ));
    t.push_str("\n[send]\n");
    t.push_str(&format!("to = \"{}\"\nbind = \"{}\"\n", a.to, a.bind));
    t.push_str(&format!(
        "repair = {}\ninterleave = {}\npasses = {}\npass_gap = {}\nmax_mbps = {}\nmax_age = {}\n",
        a.repair, a.interleave, a.passes, a.pass_gap, a.max_mbps, a.max_age
    ));
    t.push_str(&format!(
        "spool = \"{}\"\nspool_max_mb = {}\n",
        a.spool.display(),
        a.spool_max_mb
    ));
    for m in &cfg.modules {
        t.push_str(&format!(
            "carousel.{} = \"{}\"\n",
            m.name,
            cfg.carousel_for(m.index)
        ));
    }
    t.push_str(&format!(
        "carousel.status = \"{}\"\n",
        cfg.carousel_for(status_endpoint(cfg))
    ));
    t.push_str("\n[receive]\n");
    t.push_str(&format!(
        "listen = \"{}\"\nstate = \"{}\"\n",
        a.listen,
        a.state.display()
    ));
    t.push_str(&format!(
        "max_objects = {}\nmax_buffer_mb = {}\nmax_partial_mb = {}\norphan_timeout = {}\nclock_skew = {}\n",
        a.max_objects, a.max_buffer_mb, a.max_partial_mb, a.orphan_timeout, a.clock_skew
    ));
    t
}

/// What both boxes must agree on for the transport, as text (hashed into
/// the status channel's transport hash).
pub fn agreed(cfg: &Config) -> String {
    match cfg.transport {
        crate::config::TransportKind::Lidi => lidi_toml(cfg),
        crate::config::TransportKind::Air => format!(
            "air symbol={} chunk={} endpoints={}",
            cfg.air.symbol,
            cfg.air.chunk,
            status_endpoint(cfg) + 1
        ),
    }
}

fn parse_lidi(cfg: &Config) -> Result<lcfg::Config, String> {
    let text = lidi_toml(cfg);
    toml::from_str::<lcfg::Config>(&text)
        .map_err(|e| format!("lidi rejected its configuration: {e}"))
}

fn raptorq(cfg: &Config) -> Result<protocol::RaptorQ, String> {
    protocol::RaptorQ::new(cfg.lidi.mtu, cfg.lidi.block, cfg.lidi.repair).map_err(|e| e.to_string())
}

/// Build the lidi sender.  Its workers are started by [`start_sender`].
pub fn new_sender(cfg: &Config) -> Result<LidiSender, String> {
    let lc = lcfg::SendConfig::from(parse_lidi(cfg)?);
    lidi_send::Sender::new(&lc, raptorq(cfg)?)
        .map_err(|e| format!("cannot create lidi sender: {e}"))
}

enum Bearer {
    Lidi(&'static LidiSender),
    Air(Arc<crate::air::AirSender>),
}

/// The input side's handle on the diode, shared by every module.
pub struct Uplink {
    bearer: Bearer,
    global: Option<Arc<TokenBucket>>,
}

impl Uplink {
    pub fn new(sender: &'static LidiSender, cfg: &Config) -> Self {
        Self {
            bearer: Bearer::Lidi(sender),
            global: cfg
                .lidi
                .max_mbps
                .map(|m| Arc::new(TokenBucket::from_mbps(m))),
        }
    }

    /// The air transport paces its own packets (`air.max_mbps`); nothing
    /// is paced on the way in.
    pub fn air(sender: Arc<crate::air::AirSender>) -> Self {
        Self {
            bearer: Bearer::Air(sender),
            global: None,
        }
    }

    fn is_air(&self) -> bool {
        matches!(self.bearer, Bearer::Air(_))
    }

    /// `inline`: a message (read now, in the caller's thread) rather than
    /// a file.
    fn enqueue(&self, endpoint: u16, source: Source, inline: bool) -> Result<(), String> {
        match &self.bearer {
            Bearer::Lidi(sender) => sender
                .new_client(
                    protocol::EndpointId::new(endpoint),
                    lcfg::EndpointOptions::default(),
                    source,
                )
                .map_err(|e| format!("lidi: {e}")),
            Bearer::Air(a) => a.submit(endpoint, source, inline),
        }
    }
}

/// One module's way into the diode.
pub struct ModuleLink {
    uplink: Arc<Uplink>,
    pub endpoint: u16,
    pub module_tag: [u8; 8],
    sealer: Arc<Sealer>,
    pacer: Option<Arc<TokenBucket>>,
}

impl ModuleLink {
    pub fn new(
        uplink: Arc<Uplink>,
        module: &crate::config::Module,
        key: Option<Vec<u8>>,
        mbps: Option<f64>,
    ) -> Self {
        Self::for_endpoint(uplink, module.index, module.tag(), key, mbps)
    }

    /// A link for an endpoint that is not a module (the status channel).
    pub fn for_endpoint(
        uplink: Arc<Uplink>,
        endpoint: u16,
        module_tag: [u8; 8],
        key: Option<Vec<u8>>,
        mbps: Option<f64>,
    ) -> Self {
        Self {
            uplink,
            endpoint,
            module_tag,
            sealer: Arc::new(Sealer::new(key)),
            pacer: mbps.map(|m| Arc::new(TokenBucket::from_mbps(m))),
        }
    }

    fn pacers(&self) -> Vec<Arc<TokenBucket>> {
        if self.uplink.is_air() {
            return Vec::new();
        }
        self.pacer
            .iter()
            .chain(self.uplink.global.iter())
            .cloned()
            .collect()
    }

    /// Send one message as one lidi transfer.  Blocks only while every
    /// lidi client slot is busy.
    pub fn send_message(&self, meta: &[u8], body: &[u8]) -> Result<(), String> {
        let bytes = envelope::message(&self.sealer, self.endpoint, self.module_tag, meta, body);
        self.uplink.enqueue(
            self.endpoint,
            Box::new(MemSource::new(bytes, self.pacers())),
            true,
        )
    }

    /// Start sending an open file; the returned channel yields the outcome
    /// once lidi has read it to the end (or given up).
    pub fn send_file(
        &self,
        meta: &[u8],
        file: File,
        size: u64,
    ) -> Result<crossbeam_channel::Receiver<FileOutcome>, String> {
        let (tx, rx) = crossbeam_channel::bounded(1);
        let src = FileSource::new(
            self.sealer.clone(),
            self.endpoint,
            self.module_tag,
            meta,
            file,
            size,
            self.pacers(),
            tx,
        );
        self.uplink.enqueue(self.endpoint, Box::new(src), false)?;
        Ok(rx)
    }
}

