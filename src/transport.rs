/// Routes each lidi transfer to its module's envelope parser.
pub struct Lifecycle {
    by_label: HashMap<PathBuf, Arc<Registration>>,
    pub aborted: AtomicU64,
}

impl Lifecycle {
    pub fn new() -> Self {
        Self {
            by_label: HashMap::new(),
            aborted: AtomicU64::new(0),
        }
    }

    pub fn register(
        &mut self,
        module: &crate::config::Module,
        key: Option<Vec<u8>>,
        inbound: Arc<dyn envelope::Inbound>,
    ) {
        let label = PathBuf::from(endpoint_label(module.index).trim_start_matches("unix:"));
        self.by_label.insert(
            label,
            Arc::new(Registration {
                endpoint: module.index,
                module_tag: module.tag(),
                inbound,
                verifier: Mutex::new(Verifier::new(key)),
            }),
        );
    }
}

impl Default for Lifecycle {
    fn default() -> Self {
        Self::new()
    }
}

/// The lidi output client type: an envelope parser.
pub struct ParserClient(envelope::Parser);

impl std::io::Write for ParserClient {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.write(buf)
    }
    fn flush(&mut self) -> std::io::Result<()> {
        self.0.flush()
    }
}

impl lidi_receive::Client for ParserClient {}

impl lidi_receive::ClientLifecycle for Lifecycle {
    fn start(
        &self,
        endpoint: &lcfg::Endpoint,
        client_id: protocol::ClientId,
    ) -> Result<Box<dyn lidi_receive::Client>, lidi_receive::Error> {
        let lcfg::Endpoint::Unix { path, .. } = endpoint else {
            return Err(lidi_receive::Error::Internal(
                "unexpected endpoint type".into(),
            ));
        };
        match self.by_label.get(path) {
            Some(reg) => {
                log::trace!(
                    "lidi client {client_id:x} -> module {:?}",
                    reg.inbound.module_name()
                );
                Ok(Box::new(ParserClient(envelope::Parser::new(reg.clone()))))
            }
            None => Err(lidi_receive::Error::Internal(format!(
                "no module for endpoint {}",
                path.display()
            ))),
        }
    }

    fn end(
        &self,
        client: Box<dyn lidi_receive::Client>,
        ok: bool,
    ) -> Result<(), lidi_receive::Error> {
        if !ok {
            self.aborted.fetch_add(1, Ordering::Relaxed);
        }
        // Dropping the parser settles the transfer: delivered if complete
        // and genuine, reported otherwise.
        drop(client);
        Ok(())
    }
}

pub type LidiReceiver = lidi_receive::Receiver<Lifecycle>;

pub fn new_receiver(cfg: &Config, lifecycle: Lifecycle) -> Result<LidiReceiver, String> {
    let lc = lcfg::ReceiveConfig::from(parse_lidi(cfg)?);
    lidi_receive::Receiver::new(&lc, raptorq(cfg)?, lifecycle)
        .map_err(|e| format!("cannot create lidi receiver: {e}"))
}

/// Check that lidi accepts the configuration, without binding anything.
pub fn new_receiver_config_check(cfg: &Config) -> Result<(), String> {
    let parsed = parse_lidi(cfg)?;
    let _ = lcfg::ReceiveConfig::from(parsed);
    raptorq(cfg).map(|_| ())
}
