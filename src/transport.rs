//! The diode transport: lidi (ANSSI-FR), embedded as a library.
//!
//! The input box runs a `lidi_send::Sender`; the output box a
//! `lidi_receive::Receiver`.  Both are configured from the `lidi:` section
//! of config.yaml, so the parameters that must match on both sides (MTU,
//! ports, block, repair, heartbeat, max_clients) always do.
//!
//! Every DYODE module is a lidi *endpoint*: its position in config.yaml is
//! the endpoint id carried in lidi's Start block, which is how the receiver
//! knows which module a transfer belongs to.  lidi's own client sockets
//! (`tcp:`/`unix:` endpoints) are not used at all: the sender is handed
//! in-process readers, and the receiver's `ClientLifecycle` hands lidi an
//! in-process [`envelope::Parser`] instead of connecting anywhere.  The
//! `unix:` endpoint strings in the generated lidi configuration are only
//! labels.

use crate::auth::{Sealer, Verifier};
use crate::config::{Config, LidiConfig};
use crate::envelope::{self, FileOutcome, FileSource, MemSource, Registration};
use crate::ratelimit::TokenBucket;
use lidi_command_utils::config as lcfg;
use lidi_protocol as protocol;
use std::collections::HashMap;
use std::fs::File;
use std::io::Read;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

pub type Source = Box<dyn Read + Send>;
pub type LidiSender = lidi_send::Sender<Source>;

fn endpoint_label(index: u16) -> String {
    format!("unix:dyode-endpoint-{index}")
}

/// The lidi TOML for this config (the same text on both boxes).
///
/// It is what DYODE feeds to lidi's own configuration parser, and what
/// `dyode lidi-config` prints, so the transport can be inspected -- or a
/// standalone lidi-send/lidi-receive pair run with identical parameters.
pub fn lidi_toml(cfg: &Config) -> String {
    let l: &LidiConfig = &cfg.lidi;
    let ports: Vec<String> = l.ports.iter().map(u16::to_string).collect();
    let endpoints: Vec<String> = cfg
        .modules
        .iter()
        .map(|m| format!("\"{}\"", endpoint_label(m.index)))
        .collect();
    let send_bind = l
        .send_bind
        .map_or_else(|| format!("{}:0", cfg.network.in_ip), |a| a.to_string());
    let mut t = String::new();
    t.push_str("# Generated by DYODE from config.yaml.  Common parameters must be\n");
    t.push_str("# identical on both sides.\n");
    t.push_str(&format!("mtu = {}\n", l.mtu));
    t.push_str(&format!("ports = [{}]\n", ports.join(", ")));
    t.push_str(&format!("block = {}\n", l.block));
    t.push_str(&format!("repair = {}\n", l.repair));
    t.push_str(&format!("max_clients = {}\n", cfg.max_clients()));
    t.push_str(&format!("heartbeat = {}\n\n", l.heartbeat));
    t.push_str("[send]\n");
    t.push_str(&format!("to = \"{}\"\n", cfg.network.out_ip));
    t.push_str(&format!("to_bind = \"{send_bind}\"\n"));
    if let Some(m) = l.mode {
        t.push_str(&format!("mode = \"{}\"\n", m.as_str()));
    }
    if let Some(p) = l.prometheus_in {
        t.push_str(&format!("prometheus_listen = \"{p}\"\n"));
    }
    t.push_str(&format!("from = [{}]\n\n", endpoints.join(", ")));
    t.push_str("[receive]\n");
    t.push_str(&format!("from = \"{}\"\n", cfg.network.out_ip));
    if let Some(m) = l.mode {
        t.push_str(&format!("mode = \"{}\"\n", m.as_str()));
    }
    t.push_str(&format!("reset_timeout = {}\n", l.reset_timeout));
    if let Some(a) = l.abort_timeout {
        t.push_str(&format!("abort_timeout = {a}\n"));
    }
    t.push_str(&format!("client_queue_size = {}\n", l.client_queue_size));
    if let Some(p) = l.prometheus_out {
        t.push_str(&format!("prometheus_listen = \"{p}\"\n"));
    }
    t.push_str(&format!("to = [{}]\n", endpoints.join(", ")));
    t
}

fn parse_lidi(cfg: &Config) -> Result<lcfg::Config, String> {
    let text = lidi_toml(cfg);
    toml::from_str::<lcfg::Config>(&text)
        .map_err(|e| format!("lidi rejected its configuration: {e}"))
}

fn raptorq(cfg: &Config) -> Result<protocol::RaptorQ, String> {
    protocol::RaptorQ::new(cfg.lidi.mtu, cfg.lidi.block, cfg.lidi.repair).map_err(|e| e.to_string())
}

/// Build the lidi sender.  Its workers are started by [`start_sender`].
pub fn new_sender(cfg: &Config) -> Result<LidiSender, String> {
    let lc = lcfg::SendConfig::from(parse_lidi(cfg)?);
    lidi_send::Sender::new(&lc, raptorq(cfg)?)
        .map_err(|e| format!("cannot create lidi sender: {e}"))
}

/// The input side's handle on the diode, shared by every module.
pub struct Uplink {
    sender: &'static LidiSender,
    global: Option<Arc<TokenBucket>>,
}

impl Uplink {
    pub fn new(sender: &'static LidiSender, cfg: &Config) -> Self {
        Self {
            sender,
            global: cfg
                .lidi
                .max_mbps
                .map(|m| Arc::new(TokenBucket::from_mbps(m))),
        }
    }

    fn enqueue(&self, endpoint: u16, source: Source) -> Result<(), String> {
        self.sender
            .new_client(
                protocol::EndpointId::new(endpoint),
                lcfg::EndpointOptions::default(),
                source,
            )
            .map_err(|e| format!("lidi: {e}"))
    }
}

/// One module's way into the diode.
pub struct ModuleLink {
    uplink: Arc<Uplink>,
    pub endpoint: u16,
    pub module_tag: [u8; 8],
    sealer: Arc<Sealer>,
    pacer: Option<Arc<TokenBucket>>,
}

impl ModuleLink {
    pub fn new(
        uplink: Arc<Uplink>,
        module: &crate::config::Module,
        key: Option<Vec<u8>>,
        mbps: Option<f64>,
    ) -> Self {
        Self {
            uplink,
            endpoint: module.index,
            module_tag: module.tag(),
            sealer: Arc::new(Sealer::new(key)),
            pacer: mbps.map(|m| Arc::new(TokenBucket::from_mbps(m))),
        }
    }

    fn pacers(&self) -> Vec<Arc<TokenBucket>> {
        self.pacer
            .iter()
            .chain(self.uplink.global.iter())
            .cloned()
            .collect()
    }

    /// Send one message as one lidi transfer.  Blocks only while every
    /// lidi client slot is busy.
    pub fn send_message(&self, meta: &[u8], body: &[u8]) -> Result<(), String> {
        let bytes = envelope::message(&self.sealer, self.endpoint, self.module_tag, meta, body);
        self.uplink.enqueue(
            self.endpoint,
            Box::new(MemSource::new(bytes, self.pacers())),
        )
    }

    /// Start sending an open file; the returned channel yields the outcome
    /// once lidi has read it to the end (or given up).
    pub fn send_file(
        &self,
        meta: &[u8],
        file: File,
        size: u64,
    ) -> Result<crossbeam_channel::Receiver<FileOutcome>, String> {
        let (tx, rx) = crossbeam_channel::bounded(1);
        let src = FileSource::new(
            self.sealer.clone(),
            self.endpoint,
            self.module_tag,
            meta,
            file,
            size,
            self.pacers(),
            tx,
        );
        self.uplink.enqueue(self.endpoint, Box::new(src))?;
        Ok(rx)
    }
}

